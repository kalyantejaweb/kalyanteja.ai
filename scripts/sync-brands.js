function stemKey(filename) {
  return filename
    .replace(/\.[^.]+$/, "")
    .replace(/[-_]?logo$/i, "")
    .replace(/[-_\s]+/g, "")
    .toLowerCase();
}

function displayName(filename) {
  const raw = filename.replace(/\.[^.]+$/, "").replace(/[-_]?logo$/i, "");
  const key = stemKey(filename);
  if (NAME_MAP[key]) return NAME_MAP[key];
  if (NAME_MAP[raw.toLowerCase()]) return NAME_MAP[raw.toLowerCase()];
  if (/^[a-z0-9]{2,5}$/i.test(raw)) return raw.toUpperCase();
  return raw
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase())
    .trim();
}

function syncBrands() {
  if (!fs.existsSync(BRANDS_DIR)) {
    fs.mkdirSync(BRANDS_DIR, { recursive: true });
  }

  const files = fs
    .readdirSync(BRANDS_DIR)
    .filter((f) => IMAGE_EXT.has(path.extname(f).toLowerCase()))
    .filter((f) => !f.startsWith("."))
    .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

  const brands = files.map((file) => {
    const key = stemKey(file);
    const name = displayName(file);
    return {
      file,
      name,
      url: URL_MAP[key] || "#",
      textOnly: TEXT_ONLY.has(key),
    };
  });

  const banner =
    "/* Auto-generated by scripts/sync-brands.js — do not edit by hand */\n" +
    "/* Drop images into assets/images/brands then run: npm run sync-brands */\n" +
    "/* Or keep npm run watch-brands running for automatic updates */\n";

  const body =
    banner +
    "window.KALYANTEJA_BRANDS = " +
    JSON.stringify(brands, null, 2) +
    ";\n";

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body, "utf8");

  console.log(`Synced ${brands.length} brand(s) → assets/js/brands-data.js`);
  brands.forEach((b) =>
    console.log(`  - ${b.name}${b.textOnly ? " (title only)" : ""} ← ${b.file}`)
  );
  return brands;
}

if (require.main === module) {
  syncBrands();
}

module.exports = { syncBrands, BRANDS_DIR };